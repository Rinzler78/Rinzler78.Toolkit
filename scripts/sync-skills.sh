#!/usr/bin/env bash
# Refreshes the vendored skills from their public upstream, and commits the result.
#
#   sync-skills.sh              refresh, then commit on the current feature branch
#   sync-skills.sh --no-commit  refresh the working tree only
#
# The skills are committed, never fetched at run time: an update is this command on a
# branch, and a pull request someone can read. Copying from a machine's own store is
# not a source — those copies carry personal edits.
#
# scripts/skills.manifest pins each skill to a full commit of its upstream repository,
# so a refresh is reproducible and a moved branch cannot change what is vendored.
# shellcheck source=scripts/_common.sh
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

readonly MANIFEST="$REPO_ROOT/scripts/skills.manifest"
readonly DESTINATIONS=(.agents/skills .claude/skills)

# The notice is regenerated with the skills, so a pin and the licence it carries can
# never disagree.
write_notice() {
  local target=$1
  {
    printf '# Notice\n\nThe skills in this directory are vendored, unmodified, from their public upstream.\n'
    printf "Regenerated by \`%s\` from \`%s\`; do not edit.\n" scripts/sync-skills.sh scripts/skills.manifest
    local repository
    while IFS= read -r repository; do
      printf '\n## %s\n\n' "$repository"
      awk -v r="$repository" '$2 == r { printf "- `%s` at `%s`\n", $1, $3 }' "$MANIFEST_BODY"
      printf '\n'
      # Blank lines stay blank: indenting them leaves trailing whitespace the repository's own hook rewrites.
      sed '/./s/^/    /' "$WORK/licence/${repository//\//-}"
    done < <(awk '{ print $2 }' "$MANIFEST_BODY" | sort -u)
  } >"$target"
}

fetch() {
  local base=$1 repository=$2 ref=$3
  local key="${repository//\//-}-$ref"
  local archive="$WORK/$key.tar.gz"
  [[ -d "$WORK/$key" ]] && return 0
  curl --fail --silent --show-error --location "$base/$repository/tar.gz/$ref" --output "$archive" ||
    fail "cannot fetch $repository at $ref from $base"
  mkdir -p "$WORK/$key"
  tar -xzf "$archive" -C "$WORK/$key" --strip-components=1
  mkdir -p "$WORK/licence"
  cp "$WORK/$key/LICENSE" "$WORK/licence/${repository//\//-}" 2>/dev/null ||
    fail "$repository at $ref carries no LICENSE to vendor with its skills"
}

main() {
  local base=https://codeload.github.com commit=1
  while (($#)); do
    case $1 in
      --no-commit)
        commit=0
        shift
        ;;
      --base)
        [[ -n "${2:-}" ]] || fail 'usage: sync-skills.sh [--no-commit] [--base <url>]'
        base=$2
        shift 2
        ;;
      *) fail 'usage: sync-skills.sh [--no-commit] [--base <url>]' ;;
    esac
  done

  [[ -f "$MANIFEST" ]] || fail "no manifest at scripts/skills.manifest"

  WORK=$(mktemp -d)
  trap 'rm -rf "$WORK"' EXIT
  MANIFEST_BODY="$WORK/manifest"
  grep -vE '^[[:space:]]*(#|$)' "$MANIFEST" >"$MANIFEST_BODY" || true
  [[ -s "$MANIFEST_BODY" ]] || fail 'scripts/skills.manifest names no skill'

  if ((commit)); then
    local branch
    branch=$(git -C "$REPO_ROOT" rev-parse --abbrev-ref HEAD)
    [[ "$branch" == feature/* || "$branch" == hotfix/* ]] ||
      fail "the refresh is committed on a feature branch, not on '$branch': create one, or pass --no-commit"
  fi

  # One licence text is kept per repository: two pins of the same repository would share it.
  local twice
  twice=$(awk '($2 in seen) && seen[$2] != $3 { print $2; exit } { seen[$2] = $3 }' "$MANIFEST_BODY")
  [[ -z "$twice" ]] || fail "$twice is pinned at two commits: vendor one commit per repository"

  local name repository ref path
  while read -r name repository ref path; do
    [[ "$ref" =~ ^[0-9a-f]{40}$ ]] || fail "$name: '$ref' is not a full commit"
    fetch "$base" "$repository" "$ref"
    [[ -f "$WORK/${repository//\//-}-$ref/$path/SKILL.md" ]] ||
      fail "$name: $path/SKILL.md is not in $repository at $ref"
  done <"$MANIFEST_BODY"

  # A link inside an archive would be copied as a link, which a Windows checkout degrades to text.
  local links
  links=$(find "$WORK" -type l | head -3)
  [[ -z "$links" ]] || fail "symbolic link in an upstream archive: ${links//$WORK\//}"

  local destination
  for destination in "${DESTINATIONS[@]}"; do
    local root="$REPO_ROOT/$destination"
    mkdir -p "$root"
    # Only the vendored skills, the notice and the README live here.
    find "$root" -mindepth 1 -maxdepth 1 -type d -exec rm -rf {} +
    while read -r name repository ref path; do
      cp -R "$WORK/${repository//\//-}-$ref/$path" "$root/$name"
      # A tar archive carries the mode upstream committed; the facade requires every
      # shell script to be executable, wherever it sits.
      find "$root/$name" -type f -name '*.sh' -exec chmod +x {} +
    done <"$MANIFEST_BODY"
    write_notice "$root/NOTICE.md"
  done

  log "$(wc -l <"$MANIFEST_BODY" | tr -d ' ') skill(s) refreshed in ${DESTINATIONS[*]}"

  if ((commit)); then
    # Only these paths: whatever else is staged stays staged and uncommitted.
    local paths=("${DESTINATIONS[@]}" scripts/skills.manifest)
    git -C "$REPO_ROOT" add -- "${paths[@]}"
    if git -C "$REPO_ROOT" diff --cached --quiet -- "${paths[@]}"; then
      log 'nothing changed: nothing to commit'
    else
      git -C "$REPO_ROOT" commit --quiet -m 'chore(skills): refresh the vendored skills from their upstream' -- "${paths[@]}"
      log 'committed'
    fi
  fi
}

[[ "${BASH_SOURCE[0]}" == "$0" ]] && main "$@"
